def detect_device_type(mac_address, hostname=''):
    """
    識別設備類型
    
    參數:
        mac_address: MAC 地址
        hostname: 主機名稱（可選）
    
    返回:
        dict: {
            'type': '設備類型',  # Switch, Router, PC, VM, Printer, Unknown
            'vendor': '製造商',
            'confidence': '信心度',  # high, medium, low
            'icon': '圖示'
        }
    """
    if not mac_address:
        return {'type': 'Unknown', 'vendor': 'Unknown', 'confidence': 'low', 'icon': '❓'}
    
    # 標準化 MAC 地址
    mac = mac_address.strip().lower().replace('-', ':')
    oui = mac[:8] if len(mac) >= 8 else ''
    
    # 標準化主機名稱
    hostname_lower = hostname.lower() if hostname else ''
    
    # 1. 檢查是否為網路設備製造商（Switch / Router / AP）
    if oui in NETWORK_DEVICE_VENDORS:
        vendor = NETWORK_DEVICE_VENDORS[oui]
        
        # 透過主機名稱進一步判斷設備類型
        if any(keyword in hostname_lower for keyword in SWITCH_HOSTNAME_KEYWORDS):
            return {'type': 'Switch', 'vendor': vendor, 'confidence': 'high', 'icon': '🔀'}
        
        if any(keyword in hostname_lower for keyword in ROUTER_HOSTNAME_KEYWORDS):
            return {'type': 'Router', 'vendor': vendor, 'confidence': 'high', 'icon': '🌐'}
        
        if any(keyword in hostname_lower for keyword in AP_HOSTNAME_KEYWORDS):
            return {'type': 'Access Point', 'vendor': vendor, 'confidence': 'high', 'icon': '📡'}
        
        # 如果主機名稱沒有明確關鍵字，根據廠商推測
        if 'Cisco' in vendor or 'HP' in vendor or 'Aruba' in vendor or 'Juniper' in vendor:
            return {'type': 'Switch', 'vendor': vendor, 'confidence': 'medium', 'icon': '🔀'}
        
        return {'type': 'Network Device', 'vendor': vendor, 'confidence': 'medium', 'icon': '🔌'}
    
    # 2. 檢查主機名稱關鍵字（優先級）
    if any(keyword in hostname_lower for keyword in SWITCH_HOSTNAME_KEYWORDS):
        vendor = get_vendor_from_mac(mac_address)
        return {'type': 'Switch', 'vendor': vendor, 'confidence': 'medium', 'icon': '🔀'}
    
    if any(keyword in hostname_lower for keyword in ROUTER_HOSTNAME_KEYWORDS):
        vendor = get_vendor_from_mac(mac_address)
        return {'type': 'Router', 'vendor': vendor, 'confidence': 'medium', 'icon': '🌐'}
    
    if any(keyword in hostname_lower for keyword in AP_HOSTNAME_KEYWORDS):
        vendor = get_vendor_from_mac(mac_address)
        return {'type': 'Access Point', 'vendor': vendor, 'confidence': 'medium', 'icon': '📡'}
    
    if any(keyword in hostname_lower for keyword in PRINTER_HOSTNAME_KEYWORDS):
        vendor = get_vendor_from_mac(mac_address)
        return {'type': 'Printer', 'vendor': vendor, 'confidence': 'high', 'icon': '🖨️'}
    
    # 3. 檢查 VM 虛擬機 MAC 前綴
    vm_prefixes = ['00:0c:29', '00:50:56', '00:1c:14', '08:00:27', '52:54:00']
    if any(mac.startswith(prefix) for prefix in vm_prefixes):
        vendor = get_vendor_from_mac(mac_address)
        return {'type': 'Virtual Machine', 'vendor': vendor, 'confidence': 'high', 'icon': '📦'}
    
    # 4. 一般電腦設備
    vendor = get_vendor_from_mac(mac_address)
    if vendor != 'Unknown':
        # 根據廠商判斷可能的設備類型
        if vendor in ['Dell Inc.', 'HP Inc.', 'Lenovo', 'ASUSTeK']:
            return {'type': 'Computer', 'vendor': vendor, 'confidence': 'medium', 'icon': '💻'}
        if vendor in ['Apple, Inc.']:
            return {'type': 'Apple Device', 'vendor': vendor, 'confidence': 'medium', 'icon': '🍎'}
        if vendor in ['Samsung Electronics']:
            return {'type': 'Mobile Device', 'vendor': vendor, 'confidence': 'medium', 'icon': '📱'}
    
    # 5. 無法識別
    return {'type': 'Unknown', 'vendor': vendor, 'confidence': 'low', 'icon': '❓'}


def is_network_device(mac_address, hostname=''):
    """
    快速判斷是否為網路設備（Switch, Router, AP）
    
    返回:
        bool: True 表示是網路設備
    """
    result = detect_device_type(mac_address, hostname)
    return result['type'] in ['Switch', 'Router', 'Access Point', 'Network Device']


def is_switch(mac_address, hostname=''):
    """
    快速判斷是否為 Switch
    
    返回:
        bool: True 表示是 Switch
    """
    result = detect_device_type(mac_address, hostname)
    return result['type'] == 'Switch'
